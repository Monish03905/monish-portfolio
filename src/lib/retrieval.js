function stem(word) {
  if (word.length > 4 && word.endsWith('ies')) return `${word.slice(0, -3)}y`;
  if (word.length > 4 && word.endsWith('ing')) return word.slice(0, -3);
  if (word.length > 4 && word.endsWith('ed')) return word.slice(0, -2);
  if (word.length > 3 && word.endsWith('s') && !word.endsWith('ss')) return word.slice(0, -1);
  return word;
}

export function tokenize(text) {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9+#.\s-]/g, ' ')
    .split(/\s+/)
    .map((t) => t.replace(/^[-.]+|[-.]+$/g, ''))
    .filter((t) => t.length > 1 && !STOP_WORDS.has(t) && !/^\d+$/.test(t))
    .map(stem)
    .filter(Boolean);
}

function termFrequency(tokens) {
  const tf = new Map();
  tokens.forEach((token) => tf.set(token, (tf.get(token) || 0) + 1));
  return tf;
}

export function buildIndex(docs = corpus) {
  const tokenized = docs.map((doc) => {
    const weighted = `${doc.title} ${doc.title} ${doc.text} ${(doc.tags || []).join(' ').repeat(3)}`;
    const tokens = tokenize(weighted);
    return { doc, tokens, tf: termFrequency(tokens) };
  });

  const df = new Map();
  tokenized.forEach(({ tf }) => {
    tf.forEach((_, term) => df.set(term, (df.get(term) || 0) + 1));
  });

  const total = docs.length;
  const idf = new Map();
  df.forEach((count, term) => idf.set(term, Math.log((total + 1) / (count + 0.5)) + 1));

  const vectors = tokenized.map(({ tf, tokens }) => {
    const vec = new Map();
    let norm = 0;
    tf.forEach((count, term) => {
      const weight = (1 + Math.log(count)) * (idf.get(term) || 1);
      vec.set(term, weight);
      norm += weight * weight;
    });
    return { vec, norm: Math.sqrt(norm) || 1, length: tokens.length };
  });

  return { docs, tokenized, vectors, idf, vocabulary: df.size };
}

export function search(query, index, limit = 3) {
  const baseTokens = tokenize(query);
  if (!baseTokens.length) return { results: [], tokens: [], expanded: [] };

  const expanded = new Set(baseTokens);
  baseTokens.forEach((token) => {
    (SYNONYMS[token] || []).forEach((syn) => expanded.add(stem(syn)));
    // prefix matching, e.g. "embed" → "embeddings"
    index.idf.forEach((_, term) => {
      if (term !== token && term.startsWith(token) && token.length >= 4) expanded.add(term);
    });
  });

  const queryVec = new Map();
  const primary = new Set(baseTokens);
  expanded.forEach((term) => {
    const weight = (primary.has(term) ? 2.2 : 1) * (index.idf.get(term) || 0.6);
    queryVec.set(term, weight);
  });
  let qNorm = 0;
  queryVec.forEach((w) => {
    qNorm += w * w;
  });
  qNorm = Math.sqrt(qNorm) || 1;

  const scored = index.vectors.map(({ vec, norm }, i) => {
    let dot = 0;
    const matched = [];
    queryVec.forEach((weight, term) => {
      const docWeight = vec.get(term);
      if (docWeight) {
        dot += weight * docWeight;
        if (term.length > 2) matched.push(term);
      }
    });
    return { index: i, score: dot / (qNorm * norm), matched };
  });

  scored.sort((a, b) => b.score - a.score);
  const top = scored.slice(0, limit).filter((r) => r.score > 0.01);
  const max = top[0]?.score || 1;

  return {
    tokens: baseTokens,
    expanded: [...expanded].filter((t) => !primary.has(t)),
    results: top.map((r) => {
      const doc = index.docs[r.index];
      return {
        ...doc,
        score: Math.round((r.score / max) * 100),
        rawScore: r.score,
        matched: r.matched,
        excerpt: buildExcerpt(doc.text, r.matched),
      };
    }),
  };
}

function buildExcerpt(text, matched) {
  if (!matched.length) return text.slice(0, 240);
  const sentences = text.split(/(?<=[.!?])\s+/);
  const scored = sentences.map((sentence) => {
    const tokens = new Set(tokenize(sentence));
    const hits = matched.filter((term) => [...tokens].some((t) => t.startsWith(term) || term.startsWith(t)));
    return { sentence, hits: hits.length };
  });
  scored.sort((a, b) => b.hits - a.hits);
  const best = scored[0].sentence;
  return best.length > 320 ? `${best.slice(0, 317)}…` : best;
}
